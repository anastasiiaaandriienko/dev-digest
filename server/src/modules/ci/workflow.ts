import type { CiPostAs, CiTrigger } from '@devdigest/shared';
import { ConfigError, ValidationError } from '../../platform/errors.js';
import {
  FULL_SHA_RE,
  MAX_WORKFLOW_BYTES,
  PINNED_ACTIONS,
  RESULT_ARTIFACT,
  RESULT_FILE,
  RUNNER_NODE_VERSION,
  RUNNER_PATH,
  WORKFLOW_TEMPLATE_VERSION,
  type ActionKey,
  type PinnedAction,
} from './constants.js';

/**
 * The generated GitHub Actions workflow (AC-CI-23..29, 78; spec §9).
 *
 * Every value written into the YAML is either a constant of this module or a
 * validated enum (triggers, post_as) / integer (version) / kebab slug, so no
 * user text can inject YAML. Untrusted PR data is never interpolated into a
 * `run:` script — the runner reads it from GITHUB_EVENT_PATH itself.
 */

export interface WorkflowOptions {
  triggers: readonly CiTrigger[];
  postAs: CiPostAs;
  agentSlug: string;
  agentVersion: number;
  /** Test seam: the pinned actions (defaults to PINNED_ACTIONS). */
  actions?: Readonly<Record<ActionKey, PinnedAction>>;
}

const TRIGGER_ORDER: readonly CiTrigger[] = ['opened', 'synchronize', 'reopened'];

function pinned(actions: Readonly<Record<ActionKey, PinnedAction>>): Record<ActionKey, string> {
  const missing = (Object.keys(actions) as ActionKey[]).filter((k) => !FULL_SHA_RE.test(actions[k].sha ?? ''));
  if (missing.length > 0) {
    throw new ConfigError(
      `GitHub Actions are not pinned to confirmed commit SHAs yet: ${missing.map((k) => actions[k].uses).join(', ')}`,
    );
  }
  const ref = (k: ActionKey) => `${actions[k].uses}@${actions[k].sha} # ${actions[k].tag}`;
  return { checkout: ref('checkout'), setupNode: ref('setupNode'), uploadArtifact: ref('uploadArtifact') };
}

export function renderWorkflow(opts: WorkflowOptions): string {
  const uses = pinned(opts.actions ?? PINNED_ACTIONS);
  const types = TRIGGER_ORDER.filter((t) => opts.triggers.includes(t));
  if (types.length === 0) throw new ValidationError('Select at least one trigger');
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(opts.agentSlug)) throw new ValidationError('Invalid agent slug');
  if (!Number.isInteger(opts.agentVersion) || opts.agentVersion < 0) throw new ValidationError('Invalid agent version');
  // `none` posts nothing, but the runner still reads the PR diff.
  const prScope = opts.postAs === 'none' ? 'read' : 'write';

  return [
    `# Generated by DevDigest — workflow template v${WORKFLOW_TEMPLATE_VERSION}, agent "${opts.agentSlug}" v${opts.agentVersion}.`,
    '# The review runs the runner, manifest and skills of the PR\'s BASE commit, so a',
    '# PR cannot change what it is judged by. Fork PRs are skipped (no secrets).',
    'name: DevDigest review',
    '',
    'on:',
    '  pull_request:',
    `    types: [${types.join(', ')}]`,
    '',
    'permissions:',
    '  contents: read',
    `  pull-requests: ${prScope}`,
    '',
    'jobs:',
    '  review:',
    '    name: review',
    '    if: github.event.pull_request.head.repo.full_name == github.repository',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 15',
    '    steps:',
    '      - name: Check out the base commit',
    `        uses: ${uses.checkout}`,
    '        with:',
    '          ref: ${{ github.event.pull_request.base.sha }}',
    '          persist-credentials: false',
    '      - name: Set up Node.js',
    `        uses: ${uses.setupNode}`,
    '        with:',
    `          node-version: '${RUNNER_NODE_VERSION}'`,
    '      - name: Run DevDigest review',
    '        env:',
    '          OPENROUTER_API_KEY: ${{ secrets.OPENROUTER_API_KEY }}',
    '          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}',
    '          PR_NUMBER: ${{ github.event.pull_request.number }}',
    `          DEVDIGEST_POST_AS: ${opts.postAs}`,
    '        run: |',
    `          if [ ! -f ${RUNNER_PATH} ]; then`,
    `            echo "::notice::DevDigest runner not found on the base branch (${RUNNER_PATH}); skipping the review."`,
    '            exit 0',
    '          fi',
    `          node ${RUNNER_PATH}`,
    '      - name: Upload DevDigest result',
    '        if: always()',
    `        uses: ${uses.uploadArtifact}`,
    '        with:',
    `          name: ${RESULT_ARTIFACT}`,
    `          path: ${RESULT_FILE}`,
    '          if-no-files-found: ignore',
    '',
  ].join('\n');
}

export function utf8Bytes(text: string): number {
  return Buffer.byteLength(text, 'utf8');
}

/** An edited workflow from Preview: ≤ 64 KB UTF-8 and never `pull_request_target` (AC-CI-83, §9). */
export function assertEditedWorkflow(text: string): void {
  const bytes = utf8Bytes(text);
  if (bytes > MAX_WORKFLOW_BYTES) {
    throw new ValidationError(`The workflow is ${bytes} bytes; the limit is ${MAX_WORKFLOW_BYTES} bytes (64 KB)`, {
      bytes,
      limit: MAX_WORKFLOW_BYTES,
    });
  }
  if (text.includes('pull_request_target')) {
    throw new ValidationError('The workflow must not use pull_request_target');
  }
}
