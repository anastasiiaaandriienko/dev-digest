import { INTENT_UNAVAILABLE_LINE } from '../src/modules/reviews/intent/for-run.js';
import { DIFF, REVIEW_FIXTURE } from './helpers/run-cost-fixtures.js';

/**
 * L03 Intent block (P3) through `POST /pulls/:id/review` over HTTP + Postgres:
 * the intent is resolved ONCE per Run Review (not per agent), reaches every
 * agent's prompt, is billed separately from the review run, is reused on the
 * next run, never blocks a review, and is never generated by merely opening a PR.
 *
 * INTEGRATION TEST: needs Docker (testcontainers). Do NOT run without approval.
 * Safe run command (guard DATABASE_URL so dotenv can never point the app at the
 * dev DB; the LLMs, git, GitHub and secrets are all fakes, no network is used):
 *
 *   cd server && DATABASE_URL=postgres://guard@127.0.0.1:1/do_not_use pnpm exec vitest run test/review-intent.it.test.ts
 *
 * Notes: ONE FakeLLM class serves both roles and tells the calls apart by
 * `schemaName` (`PrIntent` = intent, anything else = review). The intent model is
 * `openrouter` (feature_models override), the two agents use `openai`. The two
 * kinds return DISTINCT costs/tokens so a leak of the intent cost into a review
 * run is visible. Review runs are fire-and-forget: tests poll `agent_runs` until
 * no run is `running`, then read the persisted trace (its `log` is the Live Log).
 */

const hasDocker = await dockerAvailable();
const d = hasDocker ? describe : describe.skip;
const config = () => loadConfig({ ...process.env, NODE_ENV: 'test' } as NodeJS.ProcessEnv);

const GOOD_INTENT = {
  intent: 'Adds a hardcoded Stripe key to the config',
  in_scope: ['config'],
  out_of_scope: ['billing logic'],
  risk_areas: ['secrets'],
  confidence: 'high',
};

const INTENT_OVERRIDE = { provider: 'openrouter', model: 'fake/intent-model' } as const;

const INTENT_COST = 0.002;
const INTENT_TOKENS = { in: 123, out: 45 };
const REVIEW_COST = 0.01;
const REVIEW_TOKENS = { in: 1000, out: 200 };

type CallKind = 'intent' | 'review';
interface RecordedCall {
  kind: CallKind;
  model: string;
  messages: ChatMessage[];
}

/** Records every call (shared log across instances) and answers by schemaName. */
class FakeLLM implements LLMProvider {
  constructor(
    readonly id: 'openai' | 'openrouter',
    private readonly log: RecordedCall[],
    private readonly behaviour: { intentFail?: () => Error | null } = {},
  ) {}
  async listModels(): Promise<never> {
    throw new Error('listModels must not be called');
  }
  async complete(): Promise<never> {
    throw new Error('complete must not be called');
  }
  async embed(): Promise<never> {
    throw new Error('embed must not be called');
  }
  async completeStructured<T>(req: StructuredRequest<T>): Promise<StructuredResult<T>> {
    const kind: CallKind = req.schemaName === INTENT_SCHEMA_NAME ? 'intent' : 'review';
    this.log.push({ kind, model: req.model, messages: req.messages as ChatMessage[] });
    if (kind === 'intent') {
      const err = this.behaviour.intentFail?.();
      if (err) throw err;
      return {
        data: GOOD_INTENT as T,
        model: req.model,
        tokensIn: INTENT_TOKENS.in,
        tokensOut: INTENT_TOKENS.out,
        costUsd: INTENT_COST,
        raw: '',
        attempts: 1,
      };
    }
    return {
      data: REVIEW_FIXTURE as T,
      model: req.model,
      tokensIn: REVIEW_TOKENS.in,
      tokensOut: REVIEW_TOKENS.out,
      costUsd: REVIEW_COST,
      raw: JSON.stringify(REVIEW_FIXTURE),
      attempts: 1,
    };
  }
}

/** GitHub that is unreachable: GET /pulls/:id must fall back to the persisted detail. */
class OfflineGitHub extends MockGitHubClient {
  override async getPullRequest(): Promise<never> {
    throw new Error('offline');
  }
}

const PATCH_A = '@@ -1,3 +1,5 @@ function send()\n context\n+retry\n+more\n context';
const PATCH_B = '@@ -10,2 +12,4 @@ class Queue\n x\n+y\n+z\n x';

d('L03 Intent in Run Review (Testcontainers pg)', () => {
  let pg: PgFixture;
  let workspaceId: string;
  let seq = 0;
  let app: FastifyInstance | null = null;
  let calls: RecordedCall[];
  let intentFail: Error | null;
  let agentIds: string[];

  const intentCalls = () => calls.filter((c) => c.kind === 'intent');
  const reviewCalls = () => calls.filter((c) => c.kind === 'review');

  beforeAll(async () => {
    pg = await startPg();
    await seed(pg.handle.db);
    const [ws] = await pg.handle.db.select().from(t.workspaces).where(eq(t.workspaces.name, DEFAULT_WORKSPACE_NAME));
    workspaceId = ws!.id;
  });
  afterAll(async () => {
    await pg?.stop();
  });

  beforeEach(async () => {
    calls = [];
    intentFail = null;
    await setFeatureModels({ review_intent: INTENT_OVERRIDE });
    await newAgents();
  });
  afterEach(async () => {
    await app?.close();
    app = null;
  });

  // ---- helpers ----------------------------------------------------------------

  async function makeApp(github: GitHubClient = new MockGitHubClient({ pulls: [] })): Promise<FastifyInstance> {
    app = await buildApp({
      config: config(),
      db: pg.handle.db,
      overrides: {
        secrets: new MockSecretsProvider({}),
        github,
        git: new MockGitClient({ diff: DIFF }),
        llm: {
          openai: new FakeLLM('openai', calls),
          openrouter: new FakeLLM('openrouter', calls, { intentFail: () => intentFail }),
        },
      },
    });
    return app;
  }

  async function setFeatureModels(value: Record<string, unknown> | null) {
    const db = pg.handle.db;
    await db.delete(t.settings).where(and(eq(t.settings.workspaceId, workspaceId), eq(t.settings.key, 'feature_models')));
    if (value) await db.insert(t.settings).values({ workspaceId, key: 'feature_models', value });
  }

  /** Exactly two enabled agents in the workspace (everything else is disabled). */
  async function newAgents() {
    const db = pg.handle.db;
    await db.update(t.agents).set({ enabled: false }).where(eq(t.agents.workspaceId, workspaceId));
    const n = seq++;
    const rows = await db
      .insert(t.agents)
      .values(
        ['A', 'B'].map((x) => ({
          workspaceId,
          name: `Intent Reviewer ${x}${n}`,
          provider: 'openai' as const,
          model: 'gpt-4.1',
          systemPrompt: `You are reviewer ${x}.`,
          strategy: 'single-pass' as const,
          repoIntel: false,
          enabled: true,
        })),
      )
      .returning();
    agentIds = rows.map((r) => r.id);
  }

  async function newPr() {
    const db = pg.handle.db;
    const name = `review-intent-${seq++}`;
    const [repo] = await db
      .insert(t.repos)
      .values({ workspaceId, owner: 'acme', name, fullName: `acme/${name}` })
      .returning();
    const [pr] = await db
      .insert(t.pullRequests)
      .values({
        workspaceId,
        repoId: repo!.id,
        number: 3000 + seq,
        title: 'Add a Stripe key',
        author: 'marisa.koch',
        branch: 'feat/stripe',
        base: 'main',
        headSha: 'a1b2c3d4',
        additions: 4,
        deletions: 0,
        filesCount: 2,
        status: 'needs_review',
        body: 'Adds the Stripe key.',
      })
      .returning();
    for (const [path, patch] of [
      ['src/config.ts', PATCH_A],
      ['src/queue.ts', PATCH_B],
    ] as const) {
      await db.insert(t.prFiles).values({ prId: pr!.id, path, additions: 2, deletions: 0, patch });
    }
    return pr!.id;
  }

  /** POST /pulls/:id/review for ALL enabled agents; returns the run ids once every run has ended. */
  async function runReview(a: FastifyInstance, prId: string): Promise<string[]> {
    const res = await a.inject({ method: 'POST', url: `/pulls/${prId}/review`, payload: { all: true } });
    expect(res.statusCode).toBe(200);
    const runIds = (res.json().runs as { run_id: string }[]).map((r) => r.run_id);
    expect(runIds).toHaveLength(2);
    const deadline = Date.now() + 30_000;
    for (;;) {
      const rows = await pg.handle.db.select().from(t.agentRuns).where(inArray(t.agentRuns.id, runIds));
      if (rows.length === runIds.length && rows.every((r) => r.status !== 'running')) break;
      if (Date.now() > deadline) throw new Error('runs did not finish in 30s');
      await new Promise((r) => setTimeout(r, 50));
    }
    return runIds;
  }

  async function loadRun(runId: string) {
    const [run] = await pg.handle.db.select().from(t.agentRuns).where(eq(t.agentRuns.id, runId));
    const [row] = await pg.handle.db.select().from(t.runTraces).where(eq(t.runTraces.runId, runId));
    const trace = row?.trace as RunTrace | undefined;
    return { run: run!, trace: trace!, log: trace?.log ?? [] };
  }

  const userOf = (c: RecordedCall) => c.messages.map((m) => m.content).join('\n');

  // ---- 1. one intent call per run, row written, every agent sees it -------------

  it('no stored intent -> exactly ONE intent call for the whole run; pr_intent written; both agents get <untrusted source="pr-intent">', async () => {
    const a = await makeApp();
    const prId = await newPr();
    expect(await getIntentRow(pg.handle.db, prId)).toBeUndefined();

    const runIds = await runReview(a, prId);

    expect(intentCalls()).toHaveLength(1);
    expect(intentCalls()[0]!.model).toBe(INTENT_OVERRIDE.model);
    expect(reviewCalls()).toHaveLength(2);
    for (const c of reviewCalls()) {
      expect(userOf(c)).toContain('<untrusted source="pr-intent">');
      expect(userOf(c)).toContain(GOOD_INTENT.intent);
    }

    const row = await getIntentRow(pg.handle.db, prId);
    expect(row).toMatchObject({
      prId,
      intent: GOOD_INTENT.intent,
      provider: 'openrouter',
      model: INTENT_OVERRIDE.model,
      tokensIn: INTENT_TOKENS.in,
      tokensOut: INTENT_TOKENS.out,
      costUsd: INTENT_COST,
    });

    for (const id of runIds) {
      const { run, log } = await loadRun(id);
      expect(run.status).toBe('done');
      const msgs = log.map((l) => l.msg);
      expect(msgs.some((m) => m.startsWith('intent: generated'))).toBe(true);
      expect(msgs.some((m) => m.startsWith('intent: attached'))).toBe(true);
    }
  });

  // ---- 2. intent cost is NOT in the run cost ------------------------------------

  it('trace.stats.cost_usd and agent_runs tokens exclude the intent call (billed separately)', async () => {
    const a = await makeApp();
    const prId = await newPr();
    const runIds = await runReview(a, prId);
    expect(intentCalls()).toHaveLength(1);

    for (const id of runIds) {
      const { run, trace } = await loadRun(id);
      expect(trace.stats.cost_usd).toBeCloseTo(REVIEW_COST, 10);
      expect(trace.stats.cost_usd).not.toBeCloseTo(REVIEW_COST + INTENT_COST, 10);
      expect(trace.stats.tokens_in).toBe(REVIEW_TOKENS.in);
      expect(trace.stats.tokens_out).toBe(REVIEW_TOKENS.out);
      expect(run.tokensIn).toBe(REVIEW_TOKENS.in);
      expect(run.tokensOut).toBe(REVIEW_TOKENS.out);
    }
  });

  // ---- 3. second run reuses the stored intent ------------------------------------

  it('second Run Review with a fresh stored intent -> 0 new intent calls; Live Log says "reused stored intent"', async () => {
    const a = await makeApp();
    const prId = await newPr();
    await runReview(a, prId);
    expect(intentCalls()).toHaveLength(1);
    const stored = await getIntentRow(pg.handle.db, prId);

    const runIds = await runReview(a, prId);

    expect(intentCalls()).toHaveLength(1); // unchanged
    expect(reviewCalls()).toHaveLength(4);
    for (const c of reviewCalls().slice(2)) {
      expect(userOf(c)).toContain('<untrusted source="pr-intent">');
    }
    expect((await getIntentRow(pg.handle.db, prId))?.generatedAt).toEqual(stored!.generatedAt);
    for (const id of runIds) {
      const { run, log } = await loadRun(id);
      expect(run.status).toBe('done');
      const msgs = log.map((l) => l.msg);
      expect(msgs).toContain('intent: reused stored intent (no model call)');
      expect(msgs.some((m) => m.startsWith('intent: generated'))).toBe(false);
    }
  });

  // ---- 4. intent failure never blocks the review ----------------------------------

  it('intent LLM failure -> runs still end done; "unavailable" info line; no error events; prompts without pr-intent', async () => {
    intentFail = new Error('provider exploded: secret-detail');
    const a = await makeApp();
    const prId = await newPr();

    const runIds = await runReview(a, prId);

    expect(intentCalls()).toHaveLength(1);
    expect(reviewCalls()).toHaveLength(2);
    for (const c of reviewCalls()) {
      expect(userOf(c)).not.toContain('pr-intent');
      expect(userOf(c)).not.toContain('## PR intent');
    }
    expect(await getIntentRow(pg.handle.db, prId)).toBeUndefined();

    for (const id of runIds) {
      const { run, trace, log } = await loadRun(id);
      expect(run.status).toBe('done');
      expect(run.error).toBeNull();
      expect(log.map((l) => l.msg)).toContain(INTENT_UNAVAILABLE_LINE);
      expect(INTENT_UNAVAILABLE_LINE).toBe('intent: unavailable — continuing without intent');
      // no 'error' kind event at all (an error line would read as a failed run in the UI)
      expect(log.filter((l) => l.kind === 'error')).toEqual([]);
      // the provider's error text never reaches the Live Log / trace
      expect(JSON.stringify(trace)).not.toContain('secret-detail');
      expect(log.some((l) => l.msg.startsWith('intent: attached'))).toBe(false);
    }
  });

  // ---- 5. trace prompt_assembly.intent -----------------------------------------------

  it('trace.prompt_assembly.intent is present when an intent was attached and absent/null when not', async () => {
    const a = await makeApp();
    const withIntent = await runReview(a, await newPr());
    for (const id of withIntent) {
      const { trace } = await loadRun(id);
      expect(typeof trace.prompt_assembly.intent).toBe('string');
      expect(trace.prompt_assembly.intent).toContain(GOOD_INTENT.intent);
      // the trace holds what was sent
      expect(userOf(reviewCalls()[0]!)).toContain(trace.prompt_assembly.intent!);
    }

    intentFail = new Error('boom');
    const without = await runReview(a, await newPr());
    for (const id of without) {
      const { run, trace } = await loadRun(id);
      expect(run.status).toBe('done');
      expect(trace.prompt_assembly.intent ?? null).toBeNull();
    }
  });

  // ---- 6. opening the PR never generates an intent -------------------------------------

  it.each([
    ['GitHub refresh succeeds', () => new MockGitHubClient({ pulls: [] })],
    ['GitHub offline (persisted detail)', () => new OfflineGitHub({ pulls: [] })],
  ] as const)('GET /pulls/:id and GET /pulls/:id/intent make 0 intent LLM calls (%s)', async (_label, github) => {
    const a = await makeApp(github());
    const prId = await newPr();

    const detail = await a.inject({ method: 'GET', url: `/pulls/${prId}` });
    expect(detail.statusCode).toBe(200);
    const intent = await a.inject({ method: 'GET', url: `/pulls/${prId}/intent` });
    expect(intent.statusCode).toBe(200);
    expect(intent.json()).toMatchObject({ pr_id: prId, intent: null });
    // and again, in the other order
    expect((await a.inject({ method: 'GET', url: `/pulls/${prId}/intent` })).statusCode).toBe(200);
    expect((await a.inject({ method: 'GET', url: `/pulls/${prId}` })).statusCode).toBe(200);

    expect(calls).toEqual([]);
    expect(await getIntentRow(pg.handle.db, prId)).toBeUndefined();
  });
});
